CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT users_username_not_blank
        CHECK (length(trim(username)) > 0)
);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(255) NOT NULL,
    author_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT messages_author_fk
        FOREIGN KEY (author_id) REFERENCES users(id),

    CONSTRAINT messages_content_not_blank
        CHECK (length(trim(content)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_messages_created
    ON messages (created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_messages_author_created
    ON messages (author_id, created_at DESC, id DESC);